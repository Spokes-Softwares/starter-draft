const PART_SETS = [
  ["brake pads", "brake cable"],
  ["chain", "cassette"],
  ["inner tube", "tyre"],
  ["gear cable", "chain"],
  ["brake pads"],
  ["spokes", "rim tape"],
] as const;

const DESCRIPTIONS = [
  "Routine safety inspection completed.",
  "Replaced worn brake pads and adjusted cable tension.",
  "Cleaned and lubricated the drivetrain.",
  "Replaced the inner tube after a puncture.",
  "Trued the wheel and replaced a broken spoke.",
  "Full service: adjusted gears, brakes, and bearings.",
] as const;

function sqlString(value: string) {
  return `'${value.replaceAll("'", "''")}'`;
}

function uuid(value: string) {
  return `'${value}'::uuid`;
}

const serviceTypeRows = TENANTS.flatMap((tenantId, tenantIndex) =>
  SERVICE_TYPE_NAMES.map(
    (typeName, typeIndex) =>
      `(${uuid(SERVICE_TYPE_IDS[tenantIndex][typeIndex])}, ${sqlString(typeName)}, ${uuid(tenantId)})`,
  ),
);

const hubStaffRows = HUB_STAFF.map(
  (hub) =>
    `(${uuid(hub.hubId)}, ${uuid(hub.adminUserId)}, ${uuid(hub.memberUserId)})`,
);

const partSetRows = PART_SETS.map(
  (parts, index) =>
    `(${index}, array[${parts.map(sqlString).join(", ")}]::text[])`,
);

const descriptionRows = DESCRIPTIONS.map(
  (description, index) => `(${index}, ${sqlString(description)})`,
);

const serviceTypeNameCase = SERVICE_TYPE_NAMES.map(
  (typeName, index) =>
    `        when ${index} then ${sqlString(typeName)}`,
).join("\n");

const sql = `-- Generated by supabase/seed/generate-maintenance-seed.ts
-- Do not edit by hand. Re-run: pnpm --filter @repo/db seed:maintenance:generate
--
-- One in four assets gets maintenance. Of those, three in five get a single
-- record and two in five get 2-4 records. Extra records on the same asset are
-- at least a week apart, and every timestamp falls in the past 18 months.

insert into public.service_types (id, type_name, tenant_id)
values
  ${serviceTypeRows.join(",\n  ")};

with numbered_assets as (
  select
    a.id,
    a.hub_id,
    th.tenant_id,
    row_number() over (order by a.hub_id, a.reference_tag, a.id) as rn
  from public.assets a
  join public.tenant_hubs th on th.id = a.hub_id
),
selected as (
  select
    na.id,
    na.hub_id,
    na.tenant_id,
    na.rn,
    case
      when (na.rn / 4) % 5 < 3 then 1
      else 2 + ((na.rn / 4) % 3)
    end as record_count
  from numbered_assets na
  where na.rn % 4 = 0
),
expanded as (
  select
    s.id as asset_id,
    s.hub_id,
    s.tenant_id,
    s.rn,
    series.n as record_index
  from selected s
  cross join lateral generate_series(1, s.record_count::integer) as series(n)
),
hub_staff as (
  select *
  from (
    values
      ${hubStaffRows.join(",\n      ")}
  ) as staff(hub_id, admin_user_id, member_user_id)
),
part_sets as (
  select *
  from (
    values
      ${partSetRows.join(",\n      ")}
  ) as parts(idx, parts)
),
descriptions as (
  select *
  from (
    values
      ${descriptionRows.join(",\n      ")}
  ) as descriptions(idx, description)
)
insert into public.maintenance_records (
  asset_id,
  parts,
  created_by,
  metadata,
  service_type,
  created_at
)
select
  e.asset_id,
  ps.parts,
  hu.id,
  jsonb_build_object('description', d.description),
  st.id,
  now()
    - (((e.rn % 450) + 1) * interval '1 day')
    - (((e.record_index - 1) * (7 + (e.rn % 21))) * interval '1 day')
from expanded e
join hub_staff hs on hs.hub_id = e.hub_id
join public.hub_users hu
  on hu.hub_id = e.hub_id
 and hu.user_id = case
   when (e.rn / 4) % 2 = 0 then hs.admin_user_id
   else hs.member_user_id
 end
join part_sets ps on ps.idx = ((e.rn + e.record_index) % ${PART_SETS.length})
join descriptions d on d.idx = ((e.rn + e.record_index) % ${DESCRIPTIONS.length})
join public.service_types st
  on st.tenant_id = e.tenant_id
 and st.type_name = case (e.rn + e.record_index) % ${SERVICE_TYPE_NAMES.length}
${serviceTypeNameCase}
      end;
`;

const outputPath = resolve(process.cwd(), "supabase/maintenance-seed.sql");

writeFileSync(outputPath, sql, "utf8");
console.log(`\x1b[33mWrote maintenance seed to ${outputPath}\x1b[0m`);
