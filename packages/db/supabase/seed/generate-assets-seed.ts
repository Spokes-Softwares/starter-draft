import { faker } from "@faker-js/faker";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

/* This file creates 1000 assets per hub and writes them into an sql file to be seeded. */

/** Hub UUIDs from auth-seed.sql */
const HUB_IDS = [
  "55555555-5555-4555-8555-555555555551", // Hub One
  "55555555-5555-4555-8555-555555555552", // Hub Two
  "55555555-5555-4555-8555-555555555553", // Hub Three
  "55555555-5555-4555-8555-555555555554", // Hub Four
] as const;

const ASSETS_PER_HUB = 1000;

function sqlString(value: string) {
  return `'${value.replaceAll("'", "''")}'`;
}

faker.seed(123);

const values = HUB_IDS.flatMap((hubId) =>
  Array.from({ length: ASSETS_PER_HUB }, () => {
    return `(${sqlString(faker.vehicle.bicycle())}, '${hubId}'::uuid)`;
  }),
);

const sql = `-- Generated by supabase/seed/generate-assets-seed.ts
-- Do not edit by hand. Re-run: pnpm --filter @repo/db seed:assets:generate

insert into public.assets (display_name, hub_id)
values
  ${values.join(",\n  ")};
`;

const outputPath = resolve(process.cwd(), "supabase/assets-seed.sql");

writeFileSync(outputPath, sql, "utf8");
console.log(
  `Wrote ${values.length} assets (${ASSETS_PER_HUB} per hub × ${HUB_IDS.length} hubs) to ${outputPath}`,
);
