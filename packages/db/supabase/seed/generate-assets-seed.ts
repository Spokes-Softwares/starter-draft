import { faker } from "@faker-js/faker";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

/* This file creates 1000 assets per hub and writes them into an sql file to be seeded. */
/* Asset table values are: 
- id
- hub_id
- reference_tag
- Asset_type
- service_status
- create_at
*/

/** Hub and tenant UUIDs from auth-seed.sql. Hubs one and two belong to tenant one. */
const HUBS = [
  {
    id: "55555555-5555-4555-8555-555555555551",
    tenantId: "44444444-4444-4444-8444-444444444441",
  },
  {
    id: "55555555-5555-4555-8555-555555555552",
    tenantId: "44444444-4444-4444-8444-444444444441",
  },
  {
    id: "55555555-5555-4555-8555-555555555553",
    tenantId: "44444444-4444-4444-8444-444444444442",
  },
  {
    id: "55555555-5555-4555-8555-555555555554",
    tenantId: "44444444-4444-4444-8444-444444444442",
  },
] as const;

const ASSETS_PER_HUB = 1000;
const ASSET_SERVICE_STATUS = [
  "out of service",
  "in service",
  "awaiting parts",
  "monitor",
];

function sqlString(value: string) {
  return `'${value.replaceAll("'", "''")}'`;
}

faker.seed(123);

/* Create the row structure using the below variable */
const rows = HUBS.flatMap((hub) =>
  Array.from({ length: ASSETS_PER_HUB }, () => {
    const serviceStatus = faker.helpers.arrayElement(ASSET_SERVICE_STATUS);
    const assetType = faker.vehicle.bicycle();
    return {
      hubId: hub.id,
      tenantId: hub.tenantId,
      serviceStatus,
      assetType,
    };
  }),
);

const assetTypes = [
  ...new Map(
    /* This is a de-duplicate of rows for asset_types,
    instead of having 4k rows of the same asset type, this just squashes them.  */
    rows.map((row) => [`${row.tenantId}:${row.assetType}`, row] as const),
  )
    /* This turns the unique rows into an array */
    .values(),
].sort((a, b) =>
  a.tenantId === b.tenantId
    ? a.assetType.localeCompare(b.assetType)
    : a.tenantId.localeCompare(b.tenantId),
);

const assetRows = rows.map((row) => {
  const referenceTag = String(
    faker.number.int({ min: 1, max: ASSETS_PER_HUB }),
  );
  return `(${sqlString(referenceTag)}, ${sqlString(row.assetType)}, ${sqlString(row.serviceStatus)}, '${row.hubId}'::uuid, '${row.tenantId}'::uuid)`;
});

const sql = `-- Generated by supabase/seed/generate-assets-seed.ts
-- Do not edit by hand. Re-run: pnpm --filter @repo/db seed:assets:generate

insert into public.asset_types (tenant_id, asset_type)
values
  ${assetTypes
    .map((row) => `('${row.tenantId}'::uuid, ${sqlString(row.assetType)})`)
    .join(",\n  ")};

insert into public.assets (reference_tag, asset_type, service_status, hub_id)
select
  v.reference_tag,
  t.id,
  v.service_status,
  v.hub_id
from (
  values
    ${assetRows.join(",\n    ")}
) as v(reference_tag, asset_type_name, service_status, hub_id, tenant_id)
join public.asset_types t
  on t.asset_type = v.asset_type_name
 and t.tenant_id = v.tenant_id;
`;

const outputPath = resolve(process.cwd(), "supabase/assets-seed.sql");

writeFileSync(outputPath, sql, "utf8");
console.log(
  `\x1b[33mSeeding ${rows.length} assets (${ASSETS_PER_HUB} per hub × ${HUBS.length} hubs) to ${outputPath}\x1b[0m`,
);
